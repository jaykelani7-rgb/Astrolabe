import { expect, test } from '@playwright/test';

test('source and symbol search paginate real matches and open canonical pinned evidence', async ({page})=>{
  await page.goto('/?view=explore');
  await page.getByRole('button',{name:'Search code',exact:true}).click();
  const search=page.getByRole('region',{name:'Code and symbol search'});
  await search.getByRole('textbox',{name:'Code or symbol query'}).fill('state');
  const found=page.waitForResponse(response=>response.url().includes('/api/search?')&&response.request().method()==='GET');
  await search.getByRole('button',{name:'Search source',exact:true}).click();
  const first=await(await found).json();
  expect(first.matches).toHaveLength(10);expect(first.nextCursor).toBeTruthy();
  await expect(search.getByRole('status')).toHaveText(`Showing 10 of ${first.total} matches`);
  const more=page.waitForRequest(request=>request.url().includes('/api/search?')&&new URL(request.url()).searchParams.has('cursor'));
  await search.getByRole('button',{name:'Load more search results'}).click();
  const nextUrl=new URL((await more).url());expect(nextUrl.searchParams.get('cursor')).toBe(first.nextCursor);expect(nextUrl.searchParams.get('q')).toBe('state');expect(nextUrl.searchParams.get('snapshotId')).toBe(first.snapshotId);
  await expect(search.locator('.code-search-results li')).toHaveCount(20);
  await search.getByRole('textbox',{name:'Code or symbol query'}).fill('setState');
  await search.getByRole('combobox',{name:'Search mode',exact:true}).selectOption('symbol');
  const symbols=page.waitForResponse(response=>response.url().includes('/api/search?')&&new URL(response.url()).searchParams.get('mode')==='symbol');
  await search.getByRole('button',{name:'Search source',exact:true}).click();
  const symbolResult=await(await symbols).json();expect(symbolResult.matches.length).toBeGreaterThan(0);expect(symbolResult.matches.every((match:{type:string})=>match.type==='symbol')).toBe(true);
  const match=symbolResult.matches[0];
  const evidence=await(await page.request.get(`/api/evidence/${match.evidenceId}?snapshotId=${match.snapshotId}`)).json();
  await search.locator('.code-search-results button').first().click();
  await expect(page.locator('.source-context')).toContainText(match.path);
  await expect(page.locator('.source-selection-label')).toHaveText(`Lines ${evidence.startLine}–${evidence.endLine}`);
  await search.getByRole('combobox',{name:'Search file scope'}).selectOption(match.fileId);
  const scoped=page.waitForResponse(response=>response.url().includes('/api/search?')&&new URL(response.url()).searchParams.get('fileId')===match.fileId);
  await search.getByRole('button',{name:'Search source',exact:true}).click();
  expect((await(await scoped).json()).matches.every((item:{fileId:string})=>item.fileId===match.fileId)).toBe(true);
});

test('snapshot selection scopes source, tasks, saved state, navigation and same-repository comparison',async({page})=>{
  await page.goto('/');
  const snapshots=(await(await page.request.get('/api/snapshots')).json()).snapshots;
  const mitt=snapshots.find((item:{snapshotId:string})=>item.snapshotId==='mitt-f9a0b5397edf');
  const second=snapshots.find((item:{snapshotId:string})=>item.snapshotId==='mitt-05f4ce67e8f1');
  const selected=page.getByRole('combobox',{name:'Repository snapshot',exact:true});
  await selected.selectOption(mitt.snapshotId);
  await expect(page.getByRole('heading',{name:`Find your bearings in ${mitt.name}.`,exact:true})).toBeVisible();
  await expect(selected).toHaveValue(mitt.snapshotId);
  await page.locator('.snapshot-comparison summary').click();
  const compare=page.getByRole('combobox',{name:'Comparison snapshot'});
  await expect(compare.locator('option')).toHaveCount(2);
  await compare.selectOption(second.snapshotId);
  await page.getByRole('button',{name:'Compare snapshots',exact:true}).click();
  await expect(page.getByRole('region',{name:'Snapshot comparison results'})).toContainText('Needs review');
  await page.locator('.snapshot-comparison summary').click();
  const guides=(await(await page.request.get(`/api/guides?snapshotId=${mitt.snapshotId}`)).json());
  const task=guides.tasks[0];
  await page.getByRole('button',{name:'Start learning',exact:true}).click();
  await page.locator('.checkpoint-index summary').click();
  const progress=page.waitForRequest(request=>request.url().includes(`/api/tasks/${task.id}/progress?`));
  await page.locator('.checkpoint-index').getByRole('button',{name:new RegExp(task.title)}).click();
  const progressUrl=new URL((await progress).url());expect(progressUrl.searchParams.get('snapshotId')).toBe(mitt.snapshotId);expect(progressUrl.searchParams.get('contentVersion')).toBe(task.contentVersion);
  await expect(page.locator('.mission-panel h3')).toHaveText(task.title);
  const hint=page.waitForRequest(request=>request.url().includes(`/api/tasks/${task.id}/hint?`));
  await page.getByRole('button',{name:'Get a hint',exact:true}).click();
  const hintUrl=new URL((await hint).url());expect(hintUrl.searchParams.get('snapshotId')).toBe(mitt.snapshotId);expect(hintUrl.searchParams.get('contentVersion')).toBe(task.contentVersion);
  await page.reload();await expect(selected).toHaveValue(mitt.snapshotId);await expect(page.locator('.mission-panel h3')).toHaveText(task.title);
  await selected.selectOption(snapshots[0].snapshotId);await expect(page.getByRole('heading',{name:'Find your bearings in Zustand.',exact:true})).toBeVisible();
  await page.goBack();await expect(selected).toHaveValue(mitt.snapshotId);await expect(page.locator('.mission-panel h3')).toHaveText(task.title);
  await page.goForward();await expect(selected).toHaveValue(snapshots[0].snapshotId);
});

test('late canonical source and search responses cannot replace a newly selected snapshot',async({page})=>{
  await page.goto('/?view=explore');
  let release!:()=>void;let intercepted!:()=>void;
  const gate=new Promise<void>(resolve=>release=resolve);const started=new Promise<void>(resolve=>intercepted=resolve);
  await page.route('**/api/repository/source?*',async route=>{const response=await route.fetch();intercepted();await gate;await route.fulfill({response});},{times:1});
  await page.getByTitle('src/middleware/persist.ts',{exact:true}).click();await started;
  await page.getByRole('combobox',{name:'Repository snapshot',exact:true}).selectOption('mitt-f9a0b5397edf');
  await expect(page.getByRole('heading',{name:'Find your bearings in developit/mitt.',exact:true})).toBeVisible();release();
  await page.getByRole('button',{name:'Explore source',exact:true}).click();
  await expect(page.locator('.source-context')).toContainText('src/index.ts');
  await expect(page.locator('.source-context')).not.toContainText('persist.ts');
  await page.getByRole('button',{name:'Search code',exact:true}).click();
  let releaseSearch!:()=>void;let interceptedSearch!:()=>void;const searchGate=new Promise<void>(resolve=>releaseSearch=resolve);const searchStarted=new Promise<void>(resolve=>interceptedSearch=resolve);
  await page.route('**/api/search?*',async route=>{const response=await route.fetch();interceptedSearch();await searchGate;await route.fulfill({response});},{times:1});
  const search=page.getByRole('region',{name:'Code and symbol search'});await search.getByRole('textbox',{name:'Code or symbol query'}).fill('emit');await search.getByRole('button',{name:'Search source',exact:true}).click();await searchStarted;
  await page.getByRole('combobox',{name:'Repository snapshot',exact:true}).selectOption('zustand-0ea8be27db13');await expect(page.getByRole('heading',{name:'Find your bearings in Zustand.',exact:true})).toBeVisible();releaseSearch();
  await page.getByRole('button',{name:'Explore source',exact:true}).click();await page.getByRole('button',{name:'Search code',exact:true}).click();await expect(page.getByRole('textbox',{name:'Code or symbol query'})).toHaveValue('');await expect(page.locator('.code-search-results')).toHaveCount(0);
});
